#!/usr/bin/env node
/**
 * Code generator: XML capability definitions → single capabilities.ts
 *
 * Matches the output format of the Java TypeScriptProcessor in arcusplatform:
 * tools/arcus-captools/src/main/java/com/iris/capability/generator/ts/TypeScriptProcessor.java
 *
 * Generates a single capabilities.ts file with exported constants for each capability/service.
 *
 * Usage: node scripts/generate-capabilities.mjs [--xml-dir <path>] [--service-dir <path>]
 */

import { readFileSync, writeFileSync, readdirSync, mkdirSync, existsSync } from 'fs';
import { join, resolve, dirname } from 'path';
import { fileURLToPath } from 'url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const PKG_ROOT = resolve(__dirname, '..');
const PROJ_ROOT = resolve(PKG_ROOT, '../..');

const XML_CAP_DIR = process.argv.includes('--xml-dir')
  ? process.argv[process.argv.indexOf('--xml-dir') + 1]
  : join(PROJ_ROOT, '../arcusplatform/common/arcus-model/src/main/resources/capability');

const XML_SVC_DIR = join(PROJ_ROOT, '../arcusplatform/common/arcus-model/src/main/resources/service');

const OUT_DIR = join(PKG_ROOT, 'src/capabilities');

// ── Minimal XML parsing ───────────────────────────────────────────────

function attr(str, name) {
  const re = new RegExp(`${name}="([^"]*)"`, 's');
  const m = str.match(re);
  return m ? m[1].replace(/&lt;/g, '<').replace(/&gt;/g, '>').replace(/&amp;/g, '&') : '';
}

function parseDefinition(xml) {
  // Detect root element type
  const isCapability = xml.includes('<c:capability');
  const isService = xml.includes('<c:service');
  if (!isCapability && !isService) return null;

  const rootTag = isCapability ? 'c:capability' : 'c:service';
  const rootMatch = xml.match(new RegExp(`<${rootTag}\\s([^>]+)>`, 's'));
  if (!rootMatch) return null;

  const rootAttrs = rootMatch[1];
  const def = {
    type: isCapability ? 'capability' : 'service',
    name: attr(rootAttrs, 'name'),
    namespace: attr(rootAttrs, 'namespace'),
    attributes: [],
    methods: [],
    events: [],
  };

  // Attributes
  const attrRegex = /<c:attribute\s([\s\S]*?)\/>/g;
  let m;
  while ((m = attrRegex.exec(xml)) !== null) {
    const a = m[1];
    const name = attr(a, 'name');
    const values = attr(a, 'values');
    def.attributes.push({
      name,
      enumValues: values ? values.split(',').map(v => v.trim()).filter(Boolean) : [],
    });
  }

  // Methods
  const methodRegex = /<c:method\s+name="([^"]+)"/g;
  while ((m = methodRegex.exec(xml)) !== null) {
    def.methods.push({ name: m[1] });
  }

  // Events
  const eventRegex = /<c:event\s+name="([^"]+)"/g;
  while ((m = eventRegex.exec(xml)) !== null) {
    def.events.push({ name: m[1] });
  }

  return def;
}

// ── Main ──────────────────────────────────────────────────────────────

const allDefs = [];

// Read capability XMLs
if (existsSync(XML_CAP_DIR)) {
  for (const file of readdirSync(XML_CAP_DIR).filter(f => f.endsWith('.xml')).sort()) {
    const xml = readFileSync(join(XML_CAP_DIR, file), 'utf-8');
    const def = parseDefinition(xml);
    if (def) allDefs.push(def);
  }
}

// Read service XMLs (if directory exists)
if (existsSync(XML_SVC_DIR)) {
  for (const file of readdirSync(XML_SVC_DIR).filter(f => f.endsWith('.xml')).sort()) {
    const xml = readFileSync(join(XML_SVC_DIR, file), 'utf-8');
    const def = parseDefinition(xml);
    if (def) allDefs.push(def);
  }
}

// Sort alphabetically by name (case-insensitive)
allDefs.sort((a, b) => a.name.localeCompare(b.name, undefined, { sensitivity: 'base' }));

// Build namespace map
const nsMap = new Map();
nsMap.set('base', 'Base');
for (const def of allDefs) {
  if (!nsMap.has(def.namespace)) {
    nsMap.set(def.namespace, def.name);
  }
}

// Generate output
const lines = [];

lines.push('// Auto-generated by arcus-captools TypeScriptGenerator — DO NOT EDIT');
lines.push('');

// Base block
lines.push('export const Base = {');
lines.push("  NAME: 'Base',");
lines.push("  NAMESPACE: 'base',");
lines.push("  ATTR_ADDRESS: 'base:address',");
lines.push("  ATTR_CAPS: 'base:caps',");
lines.push("  ATTR_ID: 'base:id',");
lines.push("  ATTR_IMAGES: 'base:images',");
lines.push("  ATTR_INSTANCES: 'base:instances',");
lines.push("  ATTR_NAME: 'base:name',");
lines.push("  ATTR_TAGS: 'base:tags',");
lines.push("  ATTR_TYPE: 'base:type',");
lines.push("  CMD_GETATTRIBUTES: 'base:GetAttributes',");
lines.push("  CMD_SETATTRIBUTES: 'base:SetAttributes',");
lines.push("  EVENT_ADDED: 'base:Added',");
lines.push("  EVENT_VALUECHANGE: 'base:ValueChange',");
lines.push("  EVENT_DELETED: 'base:Deleted',");
lines.push('} as const;');

// Definition blocks
for (const def of allDefs) {
  lines.push('');
  lines.push(`export const ${def.name} = {`);
  lines.push(`  NAME: '${def.name}',`);
  lines.push(`  NAMESPACE: '${def.namespace}',`);

  // ATTR_ constants (capabilities only)
  if (def.type === 'capability') {
    for (const a of def.attributes) {
      lines.push(`  ATTR_${a.name.toUpperCase()}: '${def.namespace}:${a.name}',`);
    }
    // Enum value constants
    for (const a of def.attributes) {
      for (const val of a.enumValues) {
        lines.push(`  ${a.name.toUpperCase()}_${val.toUpperCase()}: '${val}',`);
      }
    }
  }

  // CMD_ constants
  for (const method of def.methods) {
    lines.push(`  CMD_${method.name.toUpperCase()}: '${def.namespace}:${method.name}',`);
  }

  // EVENT_ constants
  for (const event of def.events) {
    lines.push(`  EVENT_${event.name.toUpperCase()}: '${def.namespace}:${event.name}',`);
  }

  lines.push('} as const;');
}

// NAMESPACE_MAP
lines.push('');
lines.push('/** Maps namespace prefix to capability/service export name(s). */');
lines.push('export const NAMESPACE_MAP: Record<string, string> = {');
const sortedNs = [...nsMap.entries()].sort((a, b) => a[0].localeCompare(b[0]));
for (const [ns, name] of sortedNs) {
  lines.push(`  '${ns}': '${name}',`);
}
lines.push('};');
lines.push('');

// Write output
mkdirSync(OUT_DIR, { recursive: true });
writeFileSync(join(OUT_DIR, 'capabilities.ts'), lines.join('\n'));

console.log(`Generated capabilities.ts with ${allDefs.length} definitions`);
